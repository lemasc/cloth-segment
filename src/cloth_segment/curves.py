"""Training curves across runs (M12): val mIoU and train loss per val check.

Answers "were the models still improving when training stopped?" from each
run's `log.jsonl` only. Never writes into a run folder and never estimates a
number: a value missing from the log is shown as missing.

- `mean`: the checkpoint selection value logged at each check
  (`dataset_mean_miou`, eval-v2): the mean of the per-dataset val mIoU over
  12 classes. If a log has no selection entries, the mean of the per-dataset
  values is used instead.
- `loss`: mean train loss over the steps since the previous check.
- `lr`: the learning rate the check step used (the schedule reaches 0 at the
  last step, so late gains partly come from the decay itself).
"""

from __future__ import annotations

import json
from collections.abc import Mapping, Sequence
from pathlib import Path

import numpy as np
from matplotlib.figure import Figure

from cloth_segment.compare import (
    GRID,
    MUTED,
    SURFACE,
    read_jsonl,
    select_series,
    train_entries,
    val_series,
)

RUN_COLOURS = ("#2a78d6", "#eb6834", "#1baf7a", "#8a5cd1", "#c9a227", "#52514e")


def run_rows(log: list[dict], datasets: Sequence[str]) -> list[dict]:
    """One row per val check: step, per-dataset val mIoU, mean, train loss, lr."""
    series = val_series(log)
    sel = select_series(log)
    steps = sorted(set().union(*(series.get(d, {}).keys() for d in datasets)) | set(sel))
    tr = train_entries(log)
    ts = np.array([x["step"] for x in tr])
    tl = np.array([x["loss"] for x in tr])
    lr_at = {x["step"]: x["lr"] for x in tr}
    rows, prev = [], 0
    for s in steps:
        per = {d: series.get(d, {}).get(s, {}).get("miou") for d in datasets}
        if s in sel:
            mean = sel[s]
        elif all(v is not None for v in per.values()):
            mean = float(np.mean(list(per.values())))
        else:
            mean = None
        m = (ts > prev) & (ts <= s) if len(ts) else np.zeros(0, bool)
        rows.append(
            {
                "step": s,
                "val": per,
                "mean": mean,
                "loss": float(tl[m].mean()) if m.any() else None,
                "lr": lr_at.get(s),
            }
        )
        prev = s
    return rows


def summarise(rows: Sequence[dict]) -> dict:
    """Best and last check, and the gain of the mean over each of the last two checks."""
    pts = [(r["step"], r["mean"]) for r in rows if r["mean"] is not None]
    if not pts:
        return {"best_step": None, "last_step": None, "last": None, "gains": []}
    best_step = max(pts, key=lambda p: p[1])[0]
    tail = pts[-3:]
    gains = [{"from": a, "to": b, "gain": vb - va} for (a, va), (b, vb) in zip(tail, tail[1:])]
    return {"best_step": best_step, "last_step": pts[-1][0], "last": pts[-1][1], "gains": gains}


def build(runs: Mapping[str, dict], runs_dir: Path, datasets: Sequence[str]) -> dict:
    """Rows and summary per run alias; `runs` maps alias -> {name, model}."""
    out = {}
    for alias, info in runs.items():
        rows = run_rows(read_jsonl(runs_dir / info["name"] / "log.jsonl"), datasets)
        out[alias] = {**info, "rows": rows, "summary": summarise(rows)}
    return out


def _f(v: float | None, fmt: str = ".4f") -> str:
    return "-" if v is None else format(v, fmt)


def markdown(res: Mapping[str, dict], datasets: Sequence[str]) -> str:
    """Summary table plus one table of every check per run."""
    md = [
        "# M12 training curves (generated by scripts/m12_curves.py; do not edit by hand)",
        "",
        "Val mIoU over 12 classes; `mean` = mean of the per-dataset values "
        "(the `dataset_mean_miou` checkpoint rule). Train loss = mean over the "
        "steps since the previous check.",
        "",
        "## Summary",
        "",
        "| run | model | best step | last step | mean at last step "
        "| gain of the last two checks | train loss, last block |",
        "|---|---|---|---|---|---|---|",
    ]
    for alias, r in res.items():
        s = r["summary"]
        gains = ", ".join(f"{g['from']}→{g['to']} {g['gain']:+.4f}" for g in s["gains"]) or "-"
        loss = r["rows"][-1]["loss"] if r["rows"] else None
        md.append(
            f"| {alias} | {r['model']} | {s['best_step']} | {s['last_step']} | "
            f"{_f(s['last'])} | {gains} | {_f(loss)} |"
        )
    for alias, r in res.items():
        md += [
            "",
            f"## {alias}: {r['model']} (`{r['name']}`)",
            "",
            "| step | " + " | ".join(datasets) + " | mean | Δ mean | train loss | lr |",
            "|---|" + "---|" * (len(datasets) + 4),
        ]
        prev = None
        for row in r["rows"]:
            delta = None if prev is None or row["mean"] is None else row["mean"] - prev
            cells = [_f(row["val"][d]) for d in datasets]
            md.append(
                f"| {row['step']} | " + " | ".join(cells) + f" | {_f(row['mean'])} | "
                f"{_f(delta, '+.4f')} | {_f(row['loss'])} | {_f(row['lr'], '.2e')} |"
            )
            prev = row["mean"] if row["mean"] is not None else prev
    return "\n".join(md) + "\n"


def write_json(res: Mapping[str, dict], path: Path) -> Path:
    path.write_text(json.dumps(res, indent=2) + "\n")
    return path


def plot(res: Mapping[str, dict], path: Path) -> Path:
    """Mean val mIoU per check and its gain over the previous check, one line per run."""
    fig = Figure(figsize=(12, 4.5), facecolor=SURFACE)
    axes = fig.subplots(1, 2)
    for i, (alias, r) in enumerate(res.items()):
        pts = [(x["step"], x["mean"]) for x in r["rows"] if x["mean"] is not None]
        if not pts:
            continue
        st, ys = zip(*pts)
        c = RUN_COLOURS[i % len(RUN_COLOURS)]
        label = f"{alias} {r['model']}"
        axes[0].plot(st, ys, color=c, lw=2, marker="o", ms=5, label=label)
        axes[1].plot(st[1:], np.diff(ys), color=c, lw=2, marker="o", ms=5, label=label)
    for ax in axes:
        ax.set_facecolor(SURFACE)
        for s in ("top", "right"):
            ax.spines[s].set_visible(False)
        ax.grid(True, color=GRID, lw=0.8)
        ax.set_xlabel("step")
    axes[0].set(title="Val mIoU, mean of LIP / CIHP / DFMM", ylabel="val mIoU (12 classes)")
    axes[1].axhline(0, color=MUTED, lw=1)
    axes[1].set(title="Gain over the previous check (every 4k steps)", ylabel="Δ val mIoU")
    axes[0].legend(loc="lower right", frameon=False)
    fig.tight_layout()
    path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(path, dpi=130)
    return path
